"""Refresh the bundled 50 m elevation grids. Requires Pillow."""
import io
import math
import subprocess
from functools import cache
from pathlib import Path

from PIL import Image

SITES = [
    ("san-gregorio", 37.326, -122.397),
    ("san-joaquin", 36.730, -120.160),
    ("sierra-foothills", 38.934, -121.082),
]
SIZE = 64
CELL_METRES = 50
ZOOM = 13


@cache
def tile(x, y):
    url = f"https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{ZOOM}/{x}/{y}.png"
    return Image.open(io.BytesIO(subprocess.check_output(["curl", "-fsSL", "--retry", "3", url]))).convert("RGB")


def sample(latitude, longitude, x, z):
    scale = 256 * 2**ZOOM
    radians = math.radians(latitude)
    pixels_per_metre = scale / (40075016.686 * math.cos(radians))
    px = int(scale * (longitude + 180) / 360 + (x + 0.5 - SIZE / 2) * CELL_METRES * pixels_per_metre)
    py = int(scale * (1 - math.asinh(math.tan(radians)) / math.pi) / 2 + (z + 0.5 - SIZE / 2) * CELL_METRES * pixels_per_metre)
    r, g, b = tile(px // 256, py // 256).getpixel((px % 256, py % 256))
    return round(r * 256 + g + b / 256 - 32768)


output = ["// Generated by scripts/sample-earth-sites.py. Rows run north to south, in metres.", "export const elevations = {"]
for key, lat, lon in SITES:
    output.append(f"  '{key}': [")
    for z in range(SIZE):
        row = [sample(lat, lon, x, z) for x in range(SIZE)]
        output.append(f"    {row},")
    output.append("  ],")
output.append("};")
(Path(__file__).resolve().parents[1] / "shared/src/terrain/elevations.ts").write_text("\n".join(output) + "\n")
