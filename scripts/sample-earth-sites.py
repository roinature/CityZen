"""Refresh the bundled 50 m elevation grids and the globe texture. Requires Pillow.

    python3 scripts/sample-earth-sites.py            # elevation grids for every site in sites.ts
    python3 scripts/sample-earth-sites.py --globe    # also client/public/textures/earth.jpg

Sites are read from shared/src/terrain/sites.ts. Grids are stored as base64 zig-zag varint
deltas (row-major, north to south) to keep the bundle small.
"""
import base64
import io
import math
import re
import subprocess
import sys
from functools import cache
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 64
CELL_METRES = 50
ZOOM = 13
SITE_PATTERN = re.compile(r"\{ id: '([^']+)'.*?latitude: (-?[\d.]+), longitude: (-?[\d.]+)(, coast: true)?")


@cache
def tile(zoom, x, y):
    url = f"https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{zoom}/{x}/{y}.png"
    return Image.open(io.BytesIO(subprocess.check_output(["curl", "-fsSL", "--retry", "3", url]))).convert("RGB")


def decode(rgb):
    r, g, b = rgb
    return r * 256 + g + b / 256 - 32768


def sample(latitude, longitude, x, z):
    scale = 256 * 2**ZOOM
    radians = math.radians(latitude)
    pixels_per_metre = scale / (40075016.686 * math.cos(radians))
    px = int(scale * (longitude + 180) / 360 + (x + 0.5 - SIZE / 2) * CELL_METRES * pixels_per_metre)
    py = int(scale * (1 - math.asinh(math.tan(radians)) / math.pi) / 2 + (z + 0.5 - SIZE / 2) * CELL_METRES * pixels_per_metre)
    return round(decode(tile(ZOOM, px // 256, py // 256).getpixel((px % 256, py % 256))))


def encode(values):
    out = bytearray()
    previous = 0
    for value in values:
        delta = value - previous
        previous = value
        zigzag = (delta << 1) ^ (delta >> 31)
        zigzag &= 0xFFFFFFFF
        while zigzag >= 0x80:
            out.append((zigzag & 0x7F) | 0x80)
            zigzag >>= 7
        out.append(zigzag)
    return base64.b64encode(bytes(out)).decode()


def stats(values, coast):
    grid = [values[z * SIZE:(z + 1) * SIZE] for z in range(SIZE)]
    h = (lambda v: max(0, v)) if coast else (lambda v: v)
    at = lambda x, z: h(grid[max(0, min(SIZE - 1, z))][max(0, min(SIZE - 1, x))])
    water = steep = 0
    for z in range(SIZE):
        for x in range(SIZE):
            if coast and grid[z][x] <= 0:
                water += 1
            elif math.hypot((at(x + 1, z) - at(x - 1, z)) / 100, (at(x, z + 1) - at(x, z - 1)) / 100) > 0.4:
                steep += 1
    n = SIZE * SIZE
    return f"{min(values)}..{max(values)} m, water {100 * water // n}%, steep {100 * steep // n}%, buildable {100 * (n - water - steep) // n}%"


def sites():
    text = (ROOT / "shared/src/terrain/sites.ts").read_text()
    return [(m[1], float(m[2]), float(m[3]), bool(m[4])) for m in SITE_PATTERN.finditer(text)]


def write_elevations():
    output = ["// Generated by scripts/sample-earth-sites.py. Base64 zig-zag varint deltas, rows north to south, metres.",
              "export const elevations = {"]
    for key, lat, lon, coast in sites():
        values = [sample(lat, lon, x, z) for z in range(SIZE) for x in range(SIZE)]
        if not coast:  # Inland tiles occasionally carry deep no-data spikes; reuse the previous cell.
            for i, value in enumerate(values):
                if value < -100:
                    values[i] = values[i - 1] if i else sorted(values)[len(values) // 2]
        print(f"{key:24} {stats(values, coast)}", flush=True)
        output.append(f"  '{key}': '{encode(values)}',")
    output.append("} as const;")
    (ROOT / "shared/src/terrain/elevations.ts").write_text("\n".join(output) + "\n")


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def ramp(stops, value):
    for (v0, c0), (v1, c1) in zip(stops, stops[1:]):
        if value <= v1:
            return lerp(c0, c1, max(0.0, min(1.0, (value - v0) / (v1 - v0))))
    return stops[-1][1]


OCEAN = [(-8000, (10, 26, 52)), (-3000, (18, 48, 86)), (-200, (34, 82, 124)), (0, (58, 116, 150))]
LAND = [(0, (86, 120, 70)), (300, (110, 136, 80)), (1000, (150, 142, 96)), (2200, (132, 108, 84)), (3600, (196, 190, 182)), (5000, (240, 240, 240))]


def write_globe(width=2048, height=1024):
    zoom = 3
    tiles = 2**zoom
    mercator = Image.new("RGB", (256 * tiles, 256 * tiles))
    for ty in range(tiles):
        for tx in range(tiles):
            mercator.paste(tile(zoom, tx, ty), (256 * tx, 256 * ty))
    span = 256 * tiles
    pixels = mercator.load()
    elevation = [[0.0] * width for _ in range(height)]
    for y in range(height):
        lat = 90 - (y + 0.5) * 180 / height
        clamped = max(-85.0, min(85.0, lat))
        my = int(span * (1 - math.asinh(math.tan(math.radians(clamped))) / math.pi) / 2)
        for x in range(width):
            mx = int((x + 0.5) * span / width) % span
            elevation[y][x] = decode(pixels[mx, min(span - 1, my)])
    out = Image.new("RGB", (width, height))
    target = out.load()
    for y in range(height):
        lat = 90 - (y + 0.5) * 180 / height
        polar = max(0.0, min(1.0, (abs(lat) - 62) / 14))
        for x in range(width):
            e = elevation[y][x]
            if e <= 0:
                color = ramp(OCEAN, e)
                if abs(lat) > 78:
                    color = lerp(color, (214, 226, 234), min(1.0, (abs(lat) - 78) / 4))
            else:
                dx = elevation[y][(x + 1) % width] - elevation[y][x - 1]
                dy = elevation[min(height - 1, y + 1)][x] - elevation[max(0, y - 1)][x]
                shade = max(0.7, min(1.25, 1 + (dy - dx) / 3000))
                color = tuple(min(255, round(c * shade)) for c in ramp(LAND, e))
                color = lerp(color, (232, 236, 240), polar)
            target[x, y] = color
    path = ROOT / "client/public/textures/earth.jpg"
    out.save(path, quality=84, optimize=True, progressive=True)
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    write_elevations()
    if "--globe" in sys.argv:
        write_globe()
